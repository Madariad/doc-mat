/**
 * Функция вычисления математической модели для интерактивного графика
 * @param {Object} task - Объект задачи из window.TASKS_DATA
 * @param {number} x - Значение параметра с ползунка
 * @param {boolean} isSecondary - Вычислить вторую функцию (для графиков пересечения двух прямых)
 * @returns {number} Значение функции y(x)
 */
window.evaluateTaskModel = function(task, x, isSecondary = false) {
  const type = isSecondary ? task.research.secondFnType : task.research.fnType;
  switch (type) {
    // Алгебра
    case "alg_01": return -2 * x * x + 40 * x - 96;
    case "alg_02_c1": return 5000 + 200 * x;
    case "alg_02_c2": return 3000 + 250 * x;
    case "alg_03": return 15 * x + 20;
    case "alg_04": return -0.5 * x * x + 6 * x + 20;
    case "alg_05_rev": return 1200 * x;
    case "alg_05_cost": return 60000 + 700 * x;
    case "alg_06": return 100 * Math.pow(0.8, x);
    case "alg_07": return 2 * Math.sin(x * Math.PI / 180);
    case "alg_08": return 0.02 * x * x - 4 * x + 500;
    case "alg_09": return 3 * x * x + 2 * x;
    case "alg_10": return -5 * x * x + 20 * x + 2;

    // Геометрия
    case "geo_01": {
      // Пирамида a=12, h=x: l = sqrt(h^2 + 36), S = 24*l (округление до 0.1 м² как в учебнике), C = 6500*S
      const l = Math.sqrt(x * x + 36);
      const S = Math.round(24 * l * 10) / 10;
      return 6500 * S;
    }
    case "geo_02": return 40 * Math.tan(x * Math.PI / 180);
    case "geo_03": {
      // Конус r=6, h=x: l = sqrt(36 + h^2), S = pi*6*l (округление до 0.1 м²), C = 7500*S
      const l = Math.sqrt(36 + x * x);
      const S = Math.round(Math.PI * 6 * l * 10) / 10;
      return 7500 * S;
    }
    case "geo_04": {
      // Купол полусфера R=x: S = 2*pi*R^2 (округление до 0.1 м²), C = 9000*S
      const S = Math.round(2 * Math.PI * x * x * 10) / 10;
      return 9000 * S;
    }
    case "geo_05": {
      // Ферма моста a=18, h=x: s = sqrt(81 + h^2) (до 0.01 м), P = 18 + 2s, C = 12000*P
      const s = Math.round(Math.sqrt(81 + x * x) * 100) / 100;
      return 12000 * (18 + 2 * s);
    }
    case "geo_06": {
      // Рампа h=1.2, alpha=x: l = 1.2 / sin(x)
      return 1.2 / Math.sin(x * Math.PI / 180);
    }
    case "geo_07": {
      // Шестиугольник a=x: S = (3*sqrt(3)/2)*a^2
      return (3 * Math.sqrt(3) / 2) * x * x;
    }
    case "geo_08": {
      // Сфера R=x: S = 4*pi*R^2 (округление до 0.1 м²), C = 4200*S
      const S = Math.round(4 * Math.PI * x * x * 10) / 10;
      return 4200 * S;
    }
    case "geo_09": {
      // Трапеция a=30, b=18, h=x: S = 24*h
      return 24 * x;
    }
    case "geo_10": {
      // Круг R=x: S = pi*R^2
      return Math.PI * x * x;
    }
    case "geo_11": {
      // Солнечная панель L=4, alpha=x: h = 4*sin(x)
      return 4 * Math.sin(x * Math.PI / 180);
    }
    case "geo_12": {
      // 12 ферм склада a=16, h=x: L = 24*sqrt(64 + h^2)
      return 24 * Math.sqrt(64 + x * x);
    }
    case "geo_13": {
      // Коробка 40x30xh: S = 2*(1200 + 70*h)
      return 2 * (1200 + 70 * x);
    }
    case "geo_14": {
      // Поле 80xb: S = 80*b
      return 80 * x;
    }
    case "geo_15": {
      // Куча щебня r=3, h=x: m = 1.6 * (1/3)*pi*9*h
      return 1.6 * Math.PI * 3 * x;
    }
    case "geo_16": {
      // Арка моста R=10, c=x: h = 10 - sqrt(100 - (c/2)^2)
      return 10 - Math.sqrt(Math.max(0, 100 - (x * x) / 4));
    }
    case "geo_17": {
      // Стеклянная пирамида a=12, h=x: S = 24 * sqrt(h^2 + 36)
      return 24 * Math.sqrt(x * x + 36);
    }
    default:
      return x;
  }
};
